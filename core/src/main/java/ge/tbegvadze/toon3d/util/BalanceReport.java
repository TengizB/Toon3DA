    private static void printWeaponRow(String weaponName, WeaponRole weaponRole,
                                       int clipSize, int damagePerShot, int reloadTicks, int ammoPerShot) {
        float sustainedDamagePerTurn = GameMath.sustainedDamagePerTurn(clipSize, damagePerShot, reloadTicks);
        float ammoEfficiency = GameMath.ammoEfficiency(damagePerShot, ammoPerShot);
        float ammoEfficiencyNormalized = ammoEfficiency / BalanceConfig.REFERENCE_AMMO_EFFICIENCY;
        float powerScore = GameMath.weaponPowerScore(sustainedDamagePerTurn, ammoEfficiencyNormalized);

        boolean insideBand = powerScore >= weaponRole.bandMinimum && powerScore <= weaponRole.bandMaximum;
        String bandText = String.format("%.0f-%.0f", weaponRole.bandMinimum, weaponRole.bandMaximum);

        System.out.printf("%-16s %-10s %8.1f %8.1f %10.1f %12s %-6s%n",
                weaponName, weaponRole.name(), sustainedDamagePerTurn, ammoEfficiency,
                powerScore, bandText, bandVerdict(insideBand, powerScore, weaponRole.bandMinimum));
    }

