    private static void printEnemyRow(String enemyName, EnemyRole enemyRole, int rawHealth,
                                      int attackDamage, int attackCadenceTurns,
                                      float positionalMultiplier, boolean useBruiserGoldenBand) {
        // Enemies currently have no dodge or flat reduction, so eHP == raw HP.
        float enemyEffectiveHitPoints = GameMath.effectiveHitPoints(rawHealth, 0f, 0f, 0f, 0f);
        float threatPoints = GameMath.threatPoints(attackDamage, attackCadenceTurns,
                enemyEffectiveHitPoints, BalanceConfig.REFERENCE_PLAYER_DPT, positionalMultiplier);
        boolean insideBand = threatPoints >= enemyRole.bandMinimum && threatPoints <= enemyRole.bandMaximum;
        String bandText = String.format("%.0f-%.0f", enemyRole.bandMinimum, enemyRole.bandMaximum);

        // Golden ratio (CONTRACT DECISION idea-A, iteration 2): TTK by the player's SUSTAINED
        // reference DPT (option b), NOT best burst. Best burst pinned TTK at 1 for anything the
        // shotgun one-shot; sustained DPT is the player's realistic kill rate and the same yardstick
        // the TP normaliser uses. TTD by enemy DPT into reference eHP (unchanged).
        int turnsToKill = GameMath.turnsToKill(enemyEffectiveHitPoints, BalanceConfig.REFERENCE_PLAYER_DPT);
        float enemyDamagePerTurn = (float) attackDamage / Math.max(1, attackCadenceTurns);
        int turnsToDie = GameMath.turnsToKill(BalanceConfig.REFERENCE_PLAYER_EHP, enemyDamagePerTurn);
        float goldenRatio = GameMath.goldenRatio(turnsToDie, turnsToKill);

        float goldenMinimum = useBruiserGoldenBand ? BalanceConfig.GOLDEN_RATIO_BRUISER_MIN : BalanceConfig.GOLDEN_RATIO_TRASH_MIN;
        float goldenMaximum = useBruiserGoldenBand ? BalanceConfig.GOLDEN_RATIO_BRUISER_MAX : BalanceConfig.GOLDEN_RATIO_TRASH_MAX;
        boolean goldenInside = goldenRatio >= goldenMinimum && goldenRatio <= goldenMaximum;

        System.out.printf("%-16s %-11s %5.0f %6d %5d %8.2f %10.1f %-6s %9.1f %-6s%n",
                enemyName, enemyRole.name(), enemyEffectiveHitPoints, attackDamage, attackCadenceTurns,
                positionalMultiplier, threatPoints, bandVerdict(insideBand, threatPoints, enemyRole.bandMinimum),
                goldenRatio, bandVerdict(goldenInside, goldenRatio, goldenMinimum));
    }

